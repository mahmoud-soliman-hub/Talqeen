// Writes src/media.ts: each slot uses public/stock/<slot>.mp4|.jpg|.png when present, else the fallback image.
import fs from 'node:fs';

const SLOTS = {
  's01-founding': 'img/01-quran-light.jpg',
  's02-aims': 'img/02-halaqa.jpg',
  's03-vision': 'img/03-mashrabiya-window.jpg',
  'g01-tilawa': 'img/06-manuscripts.jpg',
  'g02-huffaz': 'img/07-graduation-ijazah.jpg',
  'g03-supervision': 'img/08-quality-dashboard.jpg',
  'g04-environment': 'img/05-tablet-modern.jpg',
  's11-waqf': 'img/09-waqf-architecture.jpg',
  's12-outro': 'img/10-mosque-wide.jpg',
};
const out = {};
for (const [slot, fallback] of Object.entries(SLOTS)) {
  const hit = ['mp4', 'jpg', 'jpeg', 'png', 'webp'].map((e) => `stock/${slot}.${e}`).find((p) => fs.existsSync(`public/${p}`));
  out[slot] = hit || fallback;
}
fs.writeFileSync('src/media.ts', `// Generated by scripts/media.mjs — do not edit by hand.\nexport const MEDIA = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log(out);
